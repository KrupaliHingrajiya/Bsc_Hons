MAX(SPI) AS MAX_SPI,
MIN(SPI) AS MIN_SPI,
(MAX(SPI)-MIN(SPI)) AS DIFFERENCE
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO
GROUP BY BRANCH
HAVING (MAX(SPI)-MIN(SPI))>1;
