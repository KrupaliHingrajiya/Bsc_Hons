-- 11. Average Result of Each Branch

SELECT BRANCH,AVG(SPI) AS AVERAGE_SPI
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO
GROUP BY BRANCH;


-- 12. Average Result of CE and ME Branch

SELECT BRANCH,AVG(SPI) AS AVERAGE_SPI
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO
WHERE BRANCH IN ('CE','ME')
GROUP BY BRANCH;


-- 13. Maximum and Minimum SPI of Each Branch

SELECT BRANCH,
MAX(SPI) AS MAX_SPI,
MIN(SPI) AS MIN_SPI
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO
GROUP BY BRANCH;


--14. Branch-wise Student Count Descending

SELECT BRANCH,
COUNT(*) AS TOTAL_STUDENTS
FROM STUDENT_INFO
GROUP BY BRANCH
