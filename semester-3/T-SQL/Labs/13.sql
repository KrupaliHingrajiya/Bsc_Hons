
CREATE TABLE STUDENT_INFO
(
    RNO INT PRIMARY KEY,
    NAME VARCHAR(50),
    BRANCH VARCHAR(10)
);



CREATE TABLE RESULT
(
    RNO INT,
    SPI DECIMAL(3,2),
    FOREIGN KEY (RNO) REFERENCES STUDENT_INFO(RNO)
);



