-- 1. Cross Join (Cartesian Product)

SELECT *
FROM STUDENT_INFO
CROSS JOIN RESULT;


-- 2. Inner Join

SELECT *
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO;


-- 3. Left Outer Join

SELECT *
FROM STUDENT_INFO S
LEFT JOIN RESULT R
ON S.RNO=R.RNO;


-- 4. Right Outer Join

SELECT *
FROM STUDENT_INFO S
RIGHT JOIN RESULT R
ON S.RNO=R.RNO;


-- 5. Full Outer Join (MySQL)

SELECT *
FROM STUDENT_INFO S
LEFT JOIN RESULT R
ON S.RNO=R.RNO

UNION

SELECT *
FROM STUDENT_INFO S
RIGHT JOIN RESULT R
ON S.RNO=R.RNO;


-- 6. Display Rno, Name, Branch and SPI

SELECT S.RNO,S.NAME,S.BRANCH,R.SPI
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO;


-- 7. CE Branch Students

SELECT S.RNO,S.NAME,S.BRANCH,R.SPI
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO
WHERE BRANCH='CE';


-- 8. Students Other Than EC Branch

SELECT S.RNO,S.NAME,S.BRANCH,R.SPI
FROM STUDENT_INFO S
INNER JOIN RESULT R
ON S.RNO=R.RNO
WHERE BRANCH<>'EC';


-- 9. SPI Greater Than 8

