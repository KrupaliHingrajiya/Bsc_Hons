-- 14. Accept STDID and return student rank based on SPI 

CREATE FUNCTION FN_STUDENT_RANK
(
    @STDID INT
)
RETURNS TABLE
AS
RETURN
(
    SELECT STDID, SNAME, CITY, SPI, BRANCH,
           RANK() OVER (ORDER BY SPI DESC) AS STUDENT_RANK
    FROM STUDENT
    WHERE STDID = @STDID
)

SELECT * FROM FN_STUDENT_RANK(103)


-- 15. Accept BRANCH and return students having second highest SPI from that branch 

CREATE FUNCTION FN_SECOND_HIGHEST_BRANCH
(
    @BRANCH VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT STDID, SNAME, CITY, SPI, BRANCH
    FROM
    (
        SELECT *,
               DENSE_RANK() OVER (ORDER BY SPI DESC) AS SPI_RANK
        FROM STUDENT
        WHERE BRANCH = @BRANCH
    ) AS T
    WHERE SPI_RANK = 2
)

SELECT * FROM FN_SECOND_HIGHEST_BRANCH('COMPUTER')