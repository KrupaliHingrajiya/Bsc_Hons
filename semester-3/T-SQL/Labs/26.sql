-- 7. Accept CITY and return students whose SPI is greater than 7 from that city 

CREATE FUNCTION FN_CITY_SPI_GREATER_7
(
    @CITY VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
    WHERE CITY = @CITY
    AND SPI > 7
)

