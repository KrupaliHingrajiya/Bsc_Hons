-- 8. Accept BRANCH and return students whose SPI is less than 8 from that branch 

CREATE FUNCTION FN_BRANCH_SPI_LESS_8
(
    @BRANCH VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
    WHERE BRANCH = @BRANCH
    AND SPI < 8
)

SELECT * FROM FN_BRANCH_SPI_LESS_8('COMPUTER')


-- 9. Accept TOPN and return top N students based on SPI 

CREATE FUNCTION FN_TOP_STUDENTS
(
    @TOPN INT
)
RETURNS TABLE
AS
RETURN
(
    SELECT TOP (@TOPN) *
    FROM STUDENT
    ORDER BY SPI DESC
)

SELECT * FROM FN_TOP_STUDENTS(5)


-- 10. Accept BRANCH and return highest SPI student from that branch 

