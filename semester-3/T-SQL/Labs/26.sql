-- 1. Display all student records 

CREATE FUNCTION FN_ALL_STUDENTS()
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
)

SELECT * FROM FN_ALL_STUDENTS()


-- 2. Accept CITY and return all students from that city 

CREATE FUNCTION FN_STUDENT_BY_CITY
(
    @CITY VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
    WHERE CITY = @CITY
)

SELECT * FROM FN_STUDENT_BY_CITY('RAJKOT')


-- 3. Accept BRANCH and return all students from that branch 

CREATE FUNCTION FN_STUDENT_BY_BRANCH
(
    @BRANCH VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
    WHERE BRANCH = @BRANCH
)

SELECT * FROM FN_STUDENT_BY_BRANCH('COMPUTER')


-- 4. Accept SPI and return students whose SPI is greater 

CREATE FUNCTION FN_SPI_GREATER
(
    @SPI DECIMAL(4,2)
)
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
    WHERE SPI > @SPI
)

SELECT * FROM FN_SPI_GREATER(8.00)


-- 5. Accept MIN_SPI and MAX_SPI and return students whose SPI lies between the given range */

CREATE FUNCTION FN_SPI_RANGE
(
    @MIN_SPI DECIMAL(4,2),
    @MAX_SPI DECIMAL(4,2)
)
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM STUDENT
    WHERE SPI BETWEEN @MIN_SPI AND @MAX_SPI
)

SELECT * FROM FN_SPI_RANGE(7.00,9.00)


