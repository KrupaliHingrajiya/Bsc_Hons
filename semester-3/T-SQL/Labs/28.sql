-- 15. INSTEAD OF INSERT trigger to remove extra spaces
-- from FIRSTNAME and LASTNAME

CREATE OR ALTER TRIGGER TRG_REMOVE_SPACES
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
    INSERT INTO EMPLOYEE
    (
        EID,
        FIRSTNAME,
        LASTNAME,
        DEPARTMENT,
        SALARY,
        CITY,
        GENDER,
        JOININGYEAR
    )
    SELECT
        EID,
        LTRIM(RTRIM(FIRSTNAME)),
        LTRIM(RTRIM(LASTNAME)),
        DEPARTMENT,
        SALARY,
        CITY,
        GENDER,
        JOININGYEAR
    FROM inserted
END



