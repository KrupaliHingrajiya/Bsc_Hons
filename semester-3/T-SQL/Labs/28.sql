-- 11. Store updated employee details in EMPLOYEE_UPDATE_LOG

CREATE OR ALTER TRIGGER TRG_EMPLOYEE_UPDATE_LOG
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    INSERT INTO EMPLOYEE_UPDATE_LOG
    (
        EID,
        OLDSALARY,
        NEWSALARY,
        OLDDEPARTMENT,
        NEWDEPARTMENT,
        UPDATEDATE
    )
    SELECT
        D.EID,
        D.SALARY,
        I.SALARY,
        D.DEPARTMENT,
        I.DEPARTMENT,
        GETDATE()
    FROM deleted D
    INNER JOIN inserted I
    ON D.EID = I.EID
END



